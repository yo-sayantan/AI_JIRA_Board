/**
 * PR Readiness Report overlay — renders a report GENERICALLY from its block kinds, so the
 * deterministic base and the AI-enriched version use the very same component. Tabs are
 * colour-coded by tone (worst block wins) so a reader can skip the green ones.
 */
export function PrReportOverlay({
  report,
  onClose,
  onRegenerate,
  generating,
  internStatus,
  reportStyle,
}: {
  report: PrReport | null
  onClose: () => void
  /** Served mode only — kicks off a background regeneration. */
  onRegenerate?: (key: string) => void
  generating?: boolean
  internStatus?: AiInternStatus | null
  /** Settings → PDF report: the look of the deck generated by Print → Save as PDF. */
  reportStyle?: ReportStyle
}) {
  const [tabId, setTabId] = useState<string | null>(null)
  const panelRef = useRef<HTMLElement>(null)
  useDialogFocus(!!report, panelRef)
  // Reset to the first tab whenever a different report opens.
  useEffect(() => {
    setTabId(report?.tabs?.[0]?.id ?? null)
  }, [report?.key])

  // The print document is ALWAYS mounted while a report is open (CSS hides it off-paper) rather
  // than being rendered in response to the print button. Gating it on state raced the print
  // engine: afterprint could unmount it while the preview was still being generated, and the
  // export came out blank. A permanently mounted, display:none subtree has no such window.
  //
  // The save dialog takes its default filename from document.title, so every report arrived as
  // "My Jira Board". The title carries the ticket for the duration of the print; afterprint puts
  // it back, and fires on cancel too.
  const handlePrint = () => {
    if (!report) return
    const restore = document.title
    document.title = `${report.key} — PR Readiness Report`
    const onDone = () => {
      document.title = restore
      window.removeEventListener('afterprint', onDone)
    }
    window.addEventListener('afterprint', onDone)
    window.print()
  }

  // Esc closes the report BEFORE the drawer beneath gets to pop (capture + stopImmediatePropagation).
  useEffect(() => {
    if (!report) return
    const onKey = (e: KeyboardEvent) => {
      if (e.key !== 'Escape') return
      e.stopImmediatePropagation()
      e.preventDefault()
      onClose()
    }
    document.addEventListener('keydown', onKey, true)
    return () => document.removeEventListener('keydown', onKey, true)
  }, [report, onClose])

  const tabs: ReportTab[] = useMemo(
    () =>
      (report?.tabs ?? []).map((t) => ({
        ...t,
        tone: t.tone ?? worstTone((t.blocks ?? []).map((b) => b.tone)),
      })),
    [report],
  )
  const active = tabs.find((t) => t.id === tabId) ?? tabs[0]

  // The generator emits the same figures as both the header strip and an "At a glance" stats
  // block on the verdict tab. Rendering both puts identical numbers twice within one screen, so
  // the block yields to the strip. Compared by content, not title, so a tab that happens to carry
  // a genuinely different stats block still shows it.
  const blocks = useMemo(() => visibleBlocks(active?.blocks ?? [], report?.stats), [active, report?.stats])
  const blockHalfWidth = useMemo(() => halfWidthFlags(blocks), [blocks])
  const v = report?.verdict
  const vc = toneColor(v?.tone)
  const extras = report ? shareableLinks(report).filter((l) => isSafeUrl(l.href)) : []
  const ticketHref = report ? safeHref(hrefForKey(report, report.key)) : undefined

  // Portalled to <body> so print can hide its siblings with display:none. Hiding them by
  // visibility instead would keep the whole board's height in the layout, and the document would
  // paginate around content that has no ink on it — which is where the blank pages came from.
  return createPortal(
    <AnimatePresence>
      {report && (
        <motion.div
          key="jb-report"
          className="jb-report-overlay fixed inset-0 z-[80] flex items-start justify-center overflow-y-auto bg-black/60 p-4 backdrop-blur-sm md:p-8"
          {...SCRIM}
          onClick={onClose}
          role="dialog"
          aria-modal
          aria-label={`PR readiness report for ${report.key}`}
        >
          {/* Paper gets its own document, not this one restyled — see PrReportPrintDoc. Hidden on
              screen and shown in @media print, where the screen view is hidden instead. */}
          <PrReportPrintDoc report={report} tabs={tabs} style={reportStyle} />

          <motion.section
            ref={panelRef}
            tabIndex={-1}
            className="jb-dialog-panel jb-report-screen w-full max-w-[1600px] overflow-hidden rounded-2xl border border-[var(--line)] bg-[var(--bg)] shadow-2xl"
            {...DIALOG}
            onClick={(e) => e.stopPropagation()}
          >
            {/* Verdict-coloured top bar */}
            <div className="h-1.5 w-full rounded-t-2xl" style={{ background: `linear-gradient(90deg, ${vc}, ${tint(vc, 0.2)})` }} />

            {/* Header */}
            <header className="flex flex-wrap items-start gap-3 border-b border-[var(--line)] px-5 py-4 lg:px-8">
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2 text-[11px] font-bold uppercase tracking-wider text-[var(--muted)]">
                  <span>PR readiness report</span>
                  {ticketHref ? (
                    <a
                      href={ticketHref}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="font-mono normal-case tracking-normal text-[var(--link)] hover:underline"
                    >
                      {report.key}
                    </a>
                  ) : (
                    <span className="font-mono normal-case tracking-normal text-[var(--ink-soft)]">{report.key}</span>
                  )}
                  <ProvenanceChip provenance={report.enriched ? 'ai' : 'derived'} big />
                  {generating && (
                    <span className="inline-flex items-center gap-1 rounded-full border px-1.5 py-[2px] text-[10.5px] font-semibold normal-case tracking-normal" style={{ color: lift('#a855f7'), borderColor: tint('#a855f7', 0.4), background: tint('#a855f7', 0.1) }}>
                      <motion.span className="inline-flex" animate={{ rotate: 360 }} transition={{ repeat: Infinity, duration: 1.2, ease: 'linear' }}>
                        <SparkleIcon size={9} color={lift('#a855f7')} />
                      </motion.span>
                      AI report generating…
                    </span>
                  )}
                </div>
                <h2 className="mt-1 text-[17px] font-extrabold leading-snug text-[var(--ink)]">{report.title}</h2>
                {v && (
                  <p className="mt-1.5 text-[13.5px] leading-relaxed text-[var(--ink-soft)]">
                    <ReportHtml html={v.headline} report={report} inline />
                    {v.summary ? (
                      <span className="text-[var(--muted)]">
                        {' '}
                        <ReportHtml html={v.summary} report={report} inline />
                      </span>
                    ) : null}
                  </p>
                )}
                {extras.length > 0 && (
                  <div className="mt-2 flex flex-wrap gap-1.5">
                    {extras.map((l) => (
                      <a
                        key={l.href}
                        href={l.href}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="rounded-full border border-[var(--line)] bg-[var(--surface-2)] px-2 py-0.5 text-[11px] font-semibold text-[var(--link)] hover:border-[var(--muted)] hover:underline"
                      >
                        {l.label} ↗
                      </a>
                    ))}
                  </div>
                )}
              </div>
              <div className="flex shrink-0 flex-col items-end gap-2">
                <div className="flex items-center gap-2">
                  {v && (
                    <span
                      className="inline-flex items-center gap-1.5 rounded-full border px-3 py-1 text-[12px] font-extrabold"
                      style={{ color: lift(vc), borderColor: tint(vc, 0.5), background: tint(vc, 0.14) }}
                    >
                      <span className="inline-block h-2 w-2 rounded-full" style={{ background: vc }} />
                      {v.label}
                    </span>
                  )}
                  {typeof v?.score === 'number' && <ScoreRing score={v.score} color={vc} />}
                </div>
                <div className="flex items-center gap-1.5 jb-no-print">
                  <button
                    type="button"
                    onClick={handlePrint}
                    className="grid h-8 w-8 place-items-center rounded-lg border border-[var(--line)] bg-[var(--surface-solid)] text-[var(--ink-soft)] hover:border-[var(--muted)] hover:text-[var(--ink)]"
                    title="Export this report as a PDF — every tab, colour-coded, ready to share (choose “Save as PDF” in the print dialog)"
                    aria-label="Export report as PDF"
                  >
                    <PrinterIcon size={14} color="currentColor" />
                  </button>
                  {onRegenerate && (
                    <button
                      type="button"
                      onClick={() => !generating && onRegenerate(report.key)}
                      disabled={!!generating}
                      className="inline-flex items-center gap-1.5 rounded-lg border border-[var(--line)] bg-[var(--surface-solid)] px-2.5 py-1 text-[11px] font-semibold text-[var(--ink-soft)] hover:border-[var(--muted)] disabled:opacity-60"
                      title="Rebuild this report in the background (deterministic base + AI enrichment)"
                    >
                      <motion.span className="inline-flex" animate={generating ? { rotate: 360 } : { rotate: 0 }} transition={generating ? { repeat: Infinity, duration: 0.9, ease: 'linear' } : { duration: 0.2 }}>
                        <RefreshIcon size={12} color="currentColor" />
                      </motion.span>
                      {generating ? 'AI intern working' : 'Regenerate'}
                    </button>
                  )}
                  <button
                    type="button"
                    onClick={onClose}
                    className="grid h-8 w-8 place-items-center rounded-lg border border-[var(--line)] text-[var(--muted)] hover:border-[var(--muted)] hover:text-[var(--ink)]"
                    aria-label="Close report"
                  >
                    ✕
                  </button>
                </div>
              </div>
            </header>

            {/* At-a-glance stats */}
            {report.stats?.length > 0 && (
              <div className="jb-report-stats flex flex-wrap items-center border-b border-[var(--line)] px-3 py-1.5 lg:px-6">
                {report.stats.map((s, i) => (
                  <StatChip key={i} stat={s} first={i === 0} />
                ))}
              </div>
            )}

            {/* Coloured tabs */}
            <nav className="flex gap-1 overflow-x-auto border-b border-[var(--line)] px-3 pt-2 lg:px-6" role="tablist">
              {tabs.map((t) => {
                const c = toneColor(t.tone)
                const on = t.id === active?.id
                return (
                  <button
                    key={t.id}
                    role="tab"
                    id={`pr-tab-${t.id}`}
                    aria-selected={on}
                    aria-controls={`pr-panel-${t.id}`}
                    tabIndex={on ? 0 : -1}
                    onClick={() => setTabId(t.id)}
                    onKeyDown={(e) => {
                      if (e.key !== 'ArrowLeft' && e.key !== 'ArrowRight') return
                      e.preventDefault()
                      const i = tabs.findIndex((x) => x.id === t.id)
                      const next = tabs[(i + (e.key === 'ArrowRight' ? 1 : tabs.length - 1)) % tabs.length]
                      if (!next) return
                      setTabId(next.id)
                      document.getElementById(`pr-tab-${next.id}`)?.focus()
                    }}
                    className="relative flex shrink-0 items-center gap-2 rounded-t-lg px-3.5 py-2 text-[12.5px] font-semibold transition-colors"
                    style={{
                      color: on ? selectedText(c) : 'var(--ink-soft)',
                      background: on ? tint(c, 0.12) : 'transparent',
                      boxShadow: on ? `inset 0 -2px 0 ${lift(c)}` : 'none',
                    }}
                  >
                    <span className="inline-block h-2 w-2 rounded-full" style={{ background: c }} />
                    {t.title}
                    {t.badge != null && t.badge !== '' && (
                      <span className="rounded-full px-1.5 text-[10px] font-bold tabular-nums" style={{ color: lift(c), background: tint(c, 0.16) }}>
                        {t.badge}
                      </span>
                    )}
                  </button>
                )
              })}
            </nav>

            {/* Tab body — a 2-column grid on wide screens so the extra width gets used instead of
                turning into scroll. Only blocks that genuinely pair well (kv/list/links) go
                half-width, and only when there's an adjacent partner — everything else (tables,
                card grids, stats, callouts) stays full-width so no block is ever left stranded
                next to blank space. */}
            <div className="px-5 py-5 lg:px-8" role="tabpanel" id={active ? `pr-panel-${active.id}` : undefined} aria-labelledby={active ? `pr-tab-${active.id}` : undefined}>
              {active?.summary && (
                <p className="mb-3 text-[13px] text-[var(--ink-soft)]">
                  <ReportHtml html={active.summary} report={report} inline />
                </p>
              )}
              <div className="grid gap-4 lg:grid-cols-2 lg:gap-5">
                {blocks.map((b, i) => (
                  <div key={`${active?.id}:${i}`} className={blockHalfWidth[i] ? '' : 'lg:col-span-2'}>
                    <Block block={b} report={report} />
                  </div>
                ))}
              </div>
            </div>

            {/* Footer */}
            <footer className="flex flex-wrap items-center gap-x-4 gap-y-1 border-t border-[var(--line)] px-5 py-3 text-[11px] text-[var(--muted)] lg:px-8">
              <span>
                Generated {fmtDateTime(report.generatedAt, report.timeZone ?? APP_CONFIG.timeZone)}
                {report.enriched && report.enrichedAt ? ` · AI-enriched ${fmtDateTime(report.enrichedAt, report.timeZone ?? APP_CONFIG.timeZone)}` : ' · deterministic only'}
                {report.generator ? ` · ${report.generator}` : ''}
              </span>
              {internStatus && (
                <span className={internStatus.down ? 'text-[#dc2626] dark:text-[#f87171]' : internStatus.state === 'working' ? 'text-[#a855f7] dark:text-[#c084fc]' : ''}>
                  {internStatus.down
                    ? 'AI intern is down'
                    : internStatus.state === 'working' && internStatus.current?.key
                      ? `Intern enriching ${internStatus.current.key}`
                      : internStatus.state === 'working'
                        ? 'Intern working…'
                        : internStatus.lastError
                          ? `Intern: ${internStatus.lastError}`
                          : 'Intern idle'}
                </span>
              )}
              {report.sources && <span className="min-w-0 truncate">Sources: {report.sources}</span>}
              {report.warnings && report.warnings.length > 0 && (
                <span className="basis-full text-[#b45309] dark:text-[#fbbf24]">⚠ {report.warnings.join(' · ')}</span>
              )}
            </footer>
          </motion.section>
        </motion.div>
      )}
    </AnimatePresence>,
    document.body,
  )
}

